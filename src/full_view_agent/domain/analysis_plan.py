class AnalysisPlan(ContractModel):
    """???????????? + omission + ?????????

    ????????????? plan_id ??????????
    Native/LangGraph ??????``catalog_fingerprint`` ?????
    SemanticCatalog ?????execution_fingerprint???????
    ????/adapter ?????????????? plan_id???/
    ????????? Catalog ???????????????
    ?????????????????? step_id???????
    ???????DAG?Kahn ?????????????????
    ?????????????????????
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: Literal["1.0"] = ANALYSIS_PLAN_SCHEMA_VERSION
    plan_id: str = Field(min_length=1, max_length=128)
    catalog_version: str = Field(min_length=1, max_length=64)
    catalog_fingerprint: str = Field(pattern=CANONICAL_FINGERPRINT_PATTERN)
    request_id: str = Field(min_length=1, max_length=128)
    goals: tuple[AnalysisGoal, ...] = Field(min_length=1, max_length=4)
    scope_ref: AnalysisScopeRef
    steps: tuple[AnalysisStep, ...] = ()
    omissions: tuple[AnalysisOmission, ...] = ()
    constraints: PlanBudget

    @model_validator(mode="after")
    def _validate_step_graph_and_budget(self) -> "AnalysisPlan":
        step_ids = [step.step_id for step in self.steps]
        if len(set(step_ids)) != len(step_ids):
            raise ValueError("plan contains duplicate step ids")
        known = set(step_ids)
        for step in self.steps:
            if step.step_id in step.depends_on:
                raise ValueError(f"step {step.step_id} depends on itself")
            unknown = set(step.depends_on) - known
            if unknown:
                raise ValueError(
                    f"step {step.step_id} depends on unknown steps: {sorted(unknown)}"
                )
        self._require_acyclic()
        if len(self.steps) > self.constraints.max_tool_calls:
            raise ValueError(
                f"plan steps {len(self.steps)} exceed max_tool_calls budget "
                f"{self.constraints.max_tool_calls}"
            )
        if self.steps and max(step.timeout_ms for step in self.steps) > (
            self.constraints.total_timeout_ms
        ):
            raise ValueError("step timeout exceeds total timeout budget")
        return self

    def _require_acyclic(self) -> None:
        """Kahn ?????????????????

        ????????????????? A?B?A?A?B?C?A ?
        ????????????????????????????
        ??????????
        """
        in_degree = {step.step_id: 0 for step in self.steps}
        dependents: dict[str, list[str]] = {step.step_id: [] for step in self.steps}
        for step in self.steps:
            for dependency in step.depends_on:
                in_degree[step.step_id] += 1
                dependents[dependency].append(step.step_id)
        ready = [step_id for step_id, degree in in_degree.items() if degree == 0]
        processed = 0
        while ready:
            current = ready.pop()
            processed += 1
            for dependent in dependents[current]:
                in_degree[dependent] -= 1
                if in_degree[dependent] == 0:
                    ready.append(dependent)
        if processed != len(self.steps):
            cyclic = sorted(
                step_id for step_id, degree in in_degree.items() if degree > 0
            )
            raise ValueError(
                f"plan step dependencies contain a cycle involving: {cyclic}"
            )
